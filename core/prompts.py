# ============================ 工具：生成隐患分类目录文本 ============================
def _catalog_text() -> str:
    lines = []
    for code, (name, default_sev, kb_files, standards, focus) in C.HAZARD_CATALOG.items():
        std = "、".join(s[0] for s in standards) if standards else "（依据工程通用安全规范，禁止编造条款号）"
        kb = "、".join(kb_files) if kb_files else "知识库暂无全文，仅可引用标准名称"
        lines.append(f"- {code}｜{name}｜默认等级 {default_sev}｜依据：{std}｜知识库：{kb}\n  识别要点：{focus}")
    return "\n".join(lines)


